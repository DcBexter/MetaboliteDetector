"""Splits the raw dump of old_md_dump.cpp (stdin) into stage fixtures, one file per run and stage, in
crates/md-core/tests/fixtures/legacy/. tests/legacy_stages.rs reads them. Values keep the dump's 9
significant digits.

RUN.peaks.tsv       detectAllPeaks, in the old list order (by ion, then scan); line k is peak k:
                    ION  FIRST  APEX  LAST  INTERPOLATED_APEX  S/N  QUALITY  SHARPNESS
RUN.regions.tsv     detectComponents (algorithms.md §4.5), one region per line, rejected ones too:
                    BEGIN_BIN  END_BIN  PEAKS (comma-separated peak lines, with the old duplicates)
RUN.components.tsv  deconvoluteChromatogram, per component:
                    component  APEX_SCAN  RT_MS
                    model      FIRST  APEX  LAST  VALUES (comma-separated, one per scan FIRST..=LAST)
                    ion        ION  HEIGHT  FIRST  APEX  LAST  INTEGRAL  MODEL_SHARE   (ascending ion)
"""
import os
import sys
from pathlib import Path

REPO = (Path(__file__).parent / "../../../..").resolve()
OUT_DIR = (REPO / "crates/md-core/tests/fixtures/legacy").resolve()
if not OUT_DIR.is_relative_to(REPO):  # e.g. a symlinked fixture folder
    sys.exit(f"{OUT_DIR} is outside {REPO}")
STAGES = ("peaks", "regions", "components")
HEADER = "# MetaboliteDetector 3.3 (Linux), static default settings, {run}: {stage}.\n" \
         "# Generated by docs/reverse-engineering/tools/golden/make-reference.sh --stages; do not edit.\n"


def open_fixture(name):
    """Opens OUT_DIR/name for writing; the run name comes from the dump, so it must stay inside OUT_DIR."""
    path = (OUT_DIR / name).resolve()
    if not path.is_relative_to(OUT_DIR):
        sys.exit(f"{path} is outside {OUT_DIR}")
    return open(path, "w", newline="\n")


class Writer:
    def __init__(self):
        self.files = {}
        self.heights = []
        self.cpeaks = {}

    def flush_component(self):
        # One line per spectrum ion. Compound::setPeaks keeps duplicate peaks (algorithms.md §4.6); the
        # first copy of an ion stands for it.
        for ion, height in self.heights:
            f = self.cpeaks.get(float(ion))
            assert f, f"{self.name}: no peak for spectrum ion {ion}"
            self.files["components"].write("\t".join(["ion", ion, height, f[2], f[3], f[4], f[9], f[10]]) + "\n")
        self.heights, self.cpeaks = [], {}

    def close(self):
        if self.files:
            self.flush_component()
        for x in self.files.values():
            x.close()
        self.files = {}

    def run(self, f):
        self.close()
        run = os.path.basename(f[1])
        assert f[5] == "1", f"{run}: noise factor {f[5]} (the port assumes 1)"
        stem = os.path.splitext(run)[0]
        for s in STAGES:
            self.files[s] = open_fixture(f"{stem}.{s}.tsv")
            self.files[s].write(HEADER.format(run=run, stage=s))
        self.name = run

    def component(self, f):
        self.flush_component()
        self.files["components"].write(f"component\t{f[1]}\t{f[2]}\n")

    def record(self, f):
        kind = f[0]
        if kind == "run":
            self.run(f)
        elif kind == "peak":
            self.files["peaks"].write("\t".join(f[1:9]) + "\n")
        elif kind == "region":
            self.files["regions"].write("\t".join(f[1:4]) + "\n")
        elif kind == "component":
            self.component(f)
        elif kind == "model":
            self.files["components"].write("\t".join(f) + "\n")
        elif kind == "ion":
            self.heights.append((f[1], f[2]))
        elif kind == "cpeak":
            self.cpeaks.setdefault(float(f[1]), f)


def main(lines):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    w = Writer()
    for line in lines:
        w.record(line.rstrip("\n").split("\t"))
    w.close()


main(sys.stdin)
