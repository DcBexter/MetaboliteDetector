"""Splits the raw dump of old_md_dump.cpp (stdin) into stage fixtures, one file per run and stage, in the
directory given as argument (inside the repository). tests/legacy_stages.rs reads them. Values keep the
dump's 9 significant digits.

RUN.peaks.tsv       detectAllPeaks, in the old list order (by ion, then scan); line k is peak k:
                    ION  FIRST  APEX  LAST  INTERPOLATED_APEX  S/N  QUALITY  SHARPNESS
RUN.regions.tsv     detectComponents (algorithms.md §4.5), one region per line, rejected ones too:
                    BEGIN_BIN  END_BIN  PEAKS (comma-separated peak lines, with the old duplicates)
RUN.components.tsv  deconvoluteChromatogram, per component:
                    component  APEX_SCAN  RT_MS
                    model      FIRST  APEX  LAST  VALUES (comma-separated, one per scan FIRST..=LAST)
                    ion        ION  HEIGHT  FIRST  APEX  LAST  INTEGRAL  MODEL_SHARE   (ascending ion)
"""
import os
import sys

REPO = os.path.realpath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
STAGES = ("peaks", "regions", "components")
HEADER = "# MetaboliteDetector 3.3 (Linux), static default settings, {run}: {stage}.\n" \
         "# Generated by docs/reverse-engineering/tools/golden/make-reference.sh --stages; do not edit.\n"


def inside(base, path):
    """`path` resolved, refused unless it stays inside `base`."""
    path = os.path.realpath(path)
    if os.path.commonpath([base, path]) != base:
        sys.exit(f"{path} is outside {base}")
    return path


class Writer:
    def __init__(self, out_dir):
        self.out_dir = out_dir
        self.files = {}
        self.heights = []

    def close(self):
        for x in self.files.values():
            x.close()
        self.files = {}

    def run(self, f):
        self.close()
        run = os.path.basename(f[1])
        assert f[5] == "1", f"{run}: noise factor {f[5]} (the port assumes 1)"
        stem = os.path.splitext(run)[0]
        for s in STAGES:
            self.files[s] = open(inside(self.out_dir, os.path.join(self.out_dir, f"{stem}.{s}.tsv")), "w", newline="\n")
            self.files[s].write(HEADER.format(run=run, stage=s))
        self.name = run

    def component(self, f):
        self.files["components"].write(f"component\t{f[1]}\t{f[2]}\n")
        self.heights = []

    def cpeak(self, f):
        # Compound::getPeakEssentials is ordered by ion like the spectrum (golden.py).
        ion, height = self.heights.pop(0)
        assert float(ion) == float(f[1]), f"{self.name}: spectrum ion {ion} != peak ion {f[1]}"
        self.files["components"].write("\t".join(["ion", ion, height, f[2], f[3], f[4], f[9], f[10]]) + "\n")

    def record(self, f):
        kind = f[0]
        if kind == "run":
            self.run(f)
        elif kind == "peak":
            self.files["peaks"].write("\t".join(f[1:9]) + "\n")
        elif kind == "region":
            self.files["regions"].write("\t".join(f[1:4]) + "\n")
        elif kind == "component":
            self.component(f)
        elif kind == "model":
            self.files["components"].write("\t".join(f) + "\n")
        elif kind == "ion":
            self.heights.append((f[1], f[2]))
        elif kind == "cpeak":
            self.cpeak(f)


def main(lines, out_dir):
    out_dir = inside(REPO, out_dir)
    os.makedirs(out_dir, exist_ok=True)
    w = Writer(out_dir)
    for line in lines:
        w.record(line.rstrip("\n").split("\t"))
    w.close()


main(sys.stdin, sys.argv[1])
