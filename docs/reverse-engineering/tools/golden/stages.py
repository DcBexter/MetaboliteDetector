"""Splits the raw dump of old_md_dump.cpp (stdin) into stage fixtures, one file per run and stage, in the
directory given as argument. tests/legacy_stages.rs reads them. Values keep the dump's 9 significant digits.

RUN.peaks.tsv       detectAllPeaks, in the old list order (by ion, then scan); line k is peak k:
                    ION  FIRST  APEX  LAST  INTERPOLATED_APEX  S/N  QUALITY  SHARPNESS
RUN.regions.tsv     detectComponents (algorithms.md §4.5), one region per line, rejected ones too:
                    BEGIN_BIN  END_BIN  PEAKS (comma-separated peak lines, with the old duplicates)
RUN.components.tsv  deconvoluteChromatogram, per component:
                    component  APEX_SCAN  RT_MS
                    model      FIRST  APEX  LAST  VALUES (comma-separated, one per scan FIRST..=LAST)
                    ion        ION  HEIGHT  FIRST  APEX  LAST  INTEGRAL  MODEL_SHARE   (ascending ion)
"""
import os
import sys

HEADER = "# MetaboliteDetector 3.3 (Linux), static default settings, {run}: {stage}.\n" \
         "# Generated by docs/reverse-engineering/tools/golden/make-reference.sh --stages; do not edit.\n"


def main(lines, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    files = {}
    for line in lines:
        f = line.rstrip("\n").split("\t")
        if f[0] == "run":
            for x in files.values():
                x.close()
            run = f[1]
            assert f[5] == "1", f"{run}: noise factor {f[5]} (the port assumes 1)"
            stem = os.path.join(out_dir, run.rsplit(".", 1)[0])
            files = {s: open(f"{stem}.{s}.tsv", "w", newline="\n") for s in ("peaks", "regions", "components")}
            for s, x in files.items():
                x.write(HEADER.format(run=run, stage=s))
        elif f[0] == "peak":
            files["peaks"].write("\t".join(f[1:9]) + "\n")
        elif f[0] == "region":
            files["regions"].write("\t".join(f[1:4]) + "\n")
        elif f[0] == "component":
            files["components"].write(f"component\t{f[1]}\t{f[2]}\n")
            heights = []
        elif f[0] == "model":
            files["components"].write("\t".join(f) + "\n")
        elif f[0] == "ion":
            heights.append((f[1], f[2]))
        elif f[0] == "cpeak":
            # Compound::getPeakEssentials is ordered by ion like the spectrum (golden.py).
            ion, height = heights.pop(0)
            assert float(ion) == float(f[1]), f"{run}: spectrum ion {ion} != peak ion {f[1]}"
            files["components"].write("\t".join(["ion", ion, height, f[2], f[3], f[4], f[9], f[10]]) + "\n")
    for x in files.values():
        x.close()


main(sys.stdin, sys.argv[1])
