"""Reduces the raw dump of old_md_dump.cpp (stdin) to the reference file the golden test reads (stdout).

Output (tab-separated, one block per run):
  run        FILE.cdf  SCANS
  peak       ION  FIRST_SCAN  APEX_SCAN  LAST_SCAN  S/N      (only for PEAK_RUNS, to keep the file small)
  component  APEX_SCAN  ION_COUNT
  ion        ION  HEIGHT  INTEGRAL                        (the component's spectrum; integral = area)
"""
import sys

PEAK_RUNS = {"7235eg04.cdf", "7235eg20.cdf", "7235eg32.cdf"}


def main(lines):
    print("# MetaboliteDetector 3.3 (Linux) reference, static default settings.")
    print("# Generated by docs/reverse-engineering/tools/golden/make-reference.sh; do not edit.")
    run = None
    for line in lines:
        f = line.rstrip("\n").split("\t")
        if f[0] == "run":
            run = f[1]
            assert f[5] == "1", f"{run}: noise factor {f[5]} (the port assumes 1)"
            print(f"run\t{run}\t{f[3]}")
        elif f[0] == "peak" and run in PEAK_RUNS:
            print(f"peak\t{f[1]}\t{f[2]}\t{f[3]}\t{f[4]}\t{float(f[6]):.6g}")
        elif f[0] == "component":
            print(f"component\t{f[1]}\t{f[3]}")
            heights = []
        elif f[0] == "ion":
            heights.append((f[1], f[2]))
        elif f[0] == "cpeak":
            # Compound::getPeakEssentials is ordered by ion like the spectrum.
            ion, height = heights.pop(0)
            assert float(ion) == float(f[1]), f"{run}: spectrum ion {ion} != peak ion {f[1]}"
            print(f"ion\t{ion}\t{height}\t{float(f[9]):.7g}")


main(sys.stdin)
